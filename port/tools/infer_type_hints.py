#!/usr/bin/env python3
"""Writes port/TYPE_HINTS.md: the signature that pyright infers for every function in the MVP
units that lacks a parameter or return annotation.

The port needs a type for every C# member. This table gives implementers those types without
any change to the upstream source, so the oracle stays identical to the pinned commit.

Run it with the upstream interpreter, because it needs pyright from the upstream dev extra:

    .upstream/graphiti/.venv/bin/python port/tools/infer_type_hints.py
"""
from __future__ import annotations

import ast
import json
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
UP = ROOT / ".upstream/graphiti"


def collect() -> list[dict]:
    queue = json.loads((ROOT / "port/queue.json").read_text())
    found: list[dict] = []
    for unit in queue["units"]:
        if unit["notes"]:
            continue
        path = ROOT / unit["source"]
        tree = ast.parse(path.read_text(encoding="utf-8"))

        def visit(node: ast.AST, classes: list[str], nested: bool) -> None:
            for child in ast.iter_child_nodes(node):
                if isinstance(child, ast.ClassDef):
                    visit(child, [*classes, child.name], nested)
                elif isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    args = child.args
                    params = [*args.posonlyargs, *args.args, *args.kwonlyargs]
                    params += [a for a in (args.vararg, args.kwarg) if a]
                    untyped = [a.arg for a in params if a.annotation is None and a.arg not in ("self", "cls")]
                    no_return = child.returns is None and child.name != "__init__"
                    if untyped or no_return:
                        found.append(
                            {
                                "module": unit["module"],
                                "file": str(path.relative_to(UP)),
                                "line": child.lineno,
                                "name": ".".join([*classes, child.name]),
                                "nested": nested,
                                "missing": ", ".join(
                                    ([f"parameters {', '.join(untyped)}"] if untyped else [])
                                    + (["return"] if no_return else [])
                                ),
                            }
                        )
                    visit(child, classes, True)
                else:
                    visit(child, classes, nested)

        visit(tree, [], False)
    return found


def infer(found: list[dict]) -> None:
    lines = ["from typing import reveal_type"]
    probes: dict[int, dict] = {}
    for index, item in enumerate(i for i in found if not i["nested"]):
        alias = f"m{index}"
        lines.append(f"import {item['module']} as {alias}")
        lines.append(f"reveal_type({alias}.{item['name']})")
        probes[len(lines)] = item
    with tempfile.TemporaryDirectory(dir=UP) as scratch:
        probe = Path(scratch) / "probe.py"
        probe.write_text("\n".join(lines) + "\n")
        run = subprocess.run(
            [sys.executable, "-m", "pyright", "--outputjson", str(probe)], capture_output=True, text=True, cwd=UP
        )
    report = json.loads(run.stdout)
    for diagnostic in report["generalDiagnostics"]:
        line = diagnostic["range"]["start"]["line"] + 1
        message = diagnostic["message"]
        if line in probes and message.startswith('Type of "'):
            probes[line]["inferred"] = message.split(' is "', 1)[1].rstrip('"')


def main() -> int:
    found = collect()
    infer(found)
    out = [
        "# Type hints that upstream lacks",
        "",
        "Generated by `port/tools/infer_type_hints.py`. Do not edit by hand.",
        "",
        "The port needs a type for every C# member. This table lists every function in the MVP units",
        "that lacks a parameter or return annotation at the pinned commit, with the signature that",
        "pyright infers. The upstream source is not changed, so the oracle stays identical to the pin.",
        "",
        "For a nested function, read the source: pyright cannot reveal it from outside.",
        "",
        "| Function | Location | Lacks | Signature that pyright infers |",
        "| --- | --- | --- | --- |",
    ]
    for item in found:
        inferred = "Nested function. Read the source." if item["nested"] else item.get("inferred", "Not inferred.")
        inferred = inferred.replace("|", "\\|")
        out.append(f"| `{item['name']}` | `{item['file']}:{item['line']}` | {item['missing']} | `{inferred}` |")
    (ROOT / "port/TYPE_HINTS.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    missing = sum(1 for i in found if not i["nested"] and "inferred" not in i)
    print(f"infer_type_hints: {len(found)} functions, {sum(i['nested'] for i in found)} nested, {missing} not inferred")
    return 1 if missing else 0


if __name__ == "__main__":
    raise SystemExit(main())
